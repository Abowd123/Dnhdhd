// element.ts — صلابة العنصر والأحمال العقدية المكافئة.
//
// ترتيب درجات حرية العنصر: [v1, θ1, v2, θ2]
//   v: إزاحة رأسية (م) — لأعلى موجب
//   θ = dv/dx: دوران (راديان) — عكس عقارب الساعة موجب
//
// بعد المرحلة 1 لم تبقَ حاجة لصيغ قوى النهايات المقيدة للأحمال المركزة:
// التقطيع أنشأ عقدة عند كل حمل مركز وكل عزم، فصارت أحمالاً عقدية دقيقة.
// يبقى نوع حمل واحد داخل العنصر: حمل موزع شبه منحرف يغطيه بالكامل.

export type Vec4 = [number, number, number, number];
export type Mat4 = [Vec4, Vec4, Vec4, Vec4];

/** مصفوفة صلابة عنصر كمرة أويلر-برنولي منشورية (EI بوحدة kN·m²، L بالمتر) */
export function elementStiffness(EI: number, L: number): Mat4 {
  const L2 = L * L;
  const c = EI / (L2 * L);
  return [
    [12 * c, 6 * L * c, -12 * c, 6 * L * c],
    [6 * L * c, 4 * L2 * c, -6 * L * c, 2 * L2 * c],
    [-12 * c, -6 * L * c, 12 * c, -6 * L * c],
    [6 * L * c, 2 * L2 * c, -6 * L * c, 4 * L2 * c],
  ];
}

/**
 * الأحمال العقدية المكافئة لحمل موزع خطي من w1 إلى w2 (kN/m، لأسفل سالب).
 *
 * مُشتقة بالتكامل الدقيق ∫ Nᵢᵀ w(x) dx على دوال شكل هيرميت، فهي مكافئة
 * طاقياً وليست تقريباً. تُضاف مباشرة إلى متجه الأحمال العام F.
 *
 * تحقُّق من الصيغة عند الحالات الجدولية المعروفة:
 *   حمل منتظم (w1=w2=w): [wL/2, wL²/12, wL/2, -wL²/12]
 *   حمل مثلثي (w1=0):    [3wL/20, wL²/30, 7wL/20, -wL²/20]
 */
export function equivalentNodalLoads(w1: number, w2: number, L: number): Vec4 {
  const L2 = L * L;
  return [
    (L * (7 * w1 + 3 * w2)) / 20,
    (L2 * (3 * w1 + 2 * w2)) / 60,
    (L * (3 * w1 + 7 * w2)) / 20,
    -(L2 * (2 * w1 + 3 * w2)) / 60,
  ];
}

/** محصلة الحمل الموزع وعزمها الأول حول الطرف الأيسر للعنصر */
export function distributedTotals(
  w1: number,
  w2: number,
  L: number
): { Fy: number; firstMoment: number } {
  return {
    Fy: (L * (w1 + w2)) / 2,
    firstMoment: (L * L * (w1 + 2 * w2)) / 6, // ∫ (x − x₀) w dx
  };
}

/**
 * قوى نهايات العنصر: f = k·d − f_eq
 *
 * تمثّل القوى التي تبذلها العقدتان على العنصر، بترتيب درجات حرية العنصر.
 * العلاقة باصطلاحات المرحلة 3 (V موجب حين تكون محصلة الجزء الأيسر لأعلى،
 * و M موجب عند الترخيم لأسفل — شد بالألياف السفلية):
 *
 *   V(x₀⁺) = +f[0]      M(x₀⁺) = −f[1]
 *   V(x₁⁻) = −f[2]      M(x₁⁻) = +f[3]
 *
 * تُستخدم في `internalForces.ts` كثوابت تكامل للمنحنيات داخل العنصر.
 */
export function elementEndForces(k: Mat4, d: Vec4, feq: Vec4): Vec4 {
  const out: Vec4 = [0, 0, 0, 0];
  for (let i = 0; i < 4; i++) {
    let s = -feq[i];
    for (let j = 0; j < 4; j++) s += k[i][j] * d[j];
    out[i] = s;
  }
  return out;
}
